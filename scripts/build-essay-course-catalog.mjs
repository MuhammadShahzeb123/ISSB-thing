#!/usr/bin/env node
/**
 * Rebuilds app/lib/essayCourseNarration.ts from public/audio/essay-course/*.txt.
 * Text only: it never calls a TTS service. The MP3s are made by hand in
 * Google AI Studio and saved next to each script as <lesson-id>.mp3.
 */
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const dir = path.join(root, 'public/audio/essay-course');
const entries = {};
for (const name of fs.readdirSync(dir).filter((file) => file.endsWith('.txt')).sort()) {
  const id = name.replace(/\.txt$/u, '');
  entries[id] = { audio: `/audio/essay-course/${id}.mp3`, script: fs.readFileSync(path.join(dir, name), 'utf8').trim() };
}
const ts = `/* Generated by scripts/build-essay-course-catalog.mjs from public/audio/essay-course/*.txt. Do not edit by hand. */
export const essayCourseNarration: Record<string, { audio: string; script: string }> = ${JSON.stringify(entries, null, 2)};
`;
fs.writeFileSync(path.join(root, 'app/lib/essayCourseNarration.ts'), ts);
console.log(`Wrote ${Object.keys(entries).length} entries to app/lib/essayCourseNarration.ts`);
